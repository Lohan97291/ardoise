/** 4 pages cahier pour un module donné (ex: m1 → [6,7,8,9]). */
export function accesCahierPages(moduleId: string): number[] {
  const n = parseInt(moduleId.replace(/^m/, ""), 10);
  if (isNaN(n) || n < 1 || n > 35) return [];
  return [4 * n + 2, 4 * n + 3, 4 * n + 4, 4 * n + 5];
}
